						<ul>
							<h5>IV. व्यय प्रबंधन प्रकोष्ठ:</h5>
						</ul>

						<ol>a. बजट प्रभाग, आर्थिक मामलों के विभाग द्वारा निर्धारित बजट परिपत्र जारी करना।</ol>

						<ol>b. अनुदान के तहत विभिन्न घटक संगठनों/इकाइयों से प्राप्त बजट प्रस्तावों की जांच करना।</ol>

						<ol>c. बजट प्रक्रिया के प्रत्येक चरण जैसे कि बजट अनुमान (BE), संशोधित अनुमान (RE) और अंतिम आवश्यकता (FR) की स्थिति को समेकित करना और आगे की कार्रवाई के लिए वित्तीय सलाहकार (FA) को प्रस्तुत करना।</ol>

						<ol>d. स्वीकृत बजटीय प्रावधानों को संबंधित बजट नियंत्रक प्राधिकरणों को आबंटित करना।</ol>

						<ol>e. बजट अनुमान विवरण (SBEs) तैयार करना ताकि उन्हें संबंधित बजट दस्तावेजों में शामिल किया जा सके।</ol>

						<ol>f. स्वीकृत अनुदान के अनुसार व्यय की प्रगति की निगरानी करना और मासिक एवं तिमाही व्यय समीक्षा तैयार कर वित्तीय सलाहकार (FA) को प्रस्तुत करना।</ol>

						<ol>g. पुनः विनियोग आदेश (Re-appropriation Orders) प्रस्तावित करना, बचत की सरेंडर प्रक्रिया आदि के लिए वित्तीय सलाहकार (FA) से अनुमोदन प्राप्त करना।</ol>

						<ol>h. प्रधान मुख्य लेखा नियंत्रक (CCA), CBIC के साथ परामर्श कर विनियोग खाते (Appropriation Accounts) को अंतिम रूप देना और वित्तीय सलाहकार (FA) को अनुमोदन हेतु प्रस्तुत करना।</ol>

						<ol>i. वित्त पर स्थायी समिति द्वारा अनुदान की विस्तृत मांगों की परीक्षा से संबंधित आवश्यक कार्रवाई करना।</ol>

						<ol>j. व्यय मामलों से संबंधित लेखा परीक्षा संदर्भों, जैसे कि लेखा परीक्षण टिप्पणियों (Audit Paras) या लोक लेखा समिति (PAC Paras) पर कार्रवाई करना।</ol>

						<ol>k. उपरोक्त से संबंधित अन्य कोई भी कार्य।</ol>
