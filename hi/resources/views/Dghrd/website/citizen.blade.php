						<ol>h. वार्षिक प्रदर्शन मूल्यांकन रिपोर्ट (APAR) की प्राप्ति का समन्वय करना।</ol>

						<ol>i. प्रदर्शन के साथ पुरस्कार को जोड़ना और एक उपयुक्त पुरस्कार नीति तैयार करना।</ol>

						<ol>j. "बाहरी सलाहकारों" (External Consultants) के साथ समन्वय स्थापित करना ताकि व्यक्तिगत प्रदर्शन को ट्रैक, समर्थन और मॉनिटर करने के लिए एक उपयुक्त प्रणाली विकसित की जा सके और जवाबदेही सुनिश्चित की जा सके।</ol>

						<ol>k. सभी कैडरों के लिए वार्षिक प्रदर्शन मूल्यांकन (APAR) के प्रारूप की समीक्षा करना और समय-समय पर इसमें आवश्यक सुधार का सुझाव देना।</ol>

						<ol>l. समूह और व्यक्तिगत स्तरों पर संगठन के लिए निष्पक्ष लक्ष्य निर्धारण (Objective Goal Setting) के आधार पर प्रदर्शन संकेतक (Performance Indicators) विकसित करना, जिसमें जनशक्ति और बुनियादी ढांचे की सीमाओं को ध्यान में रखा जाए।</ol>

						<ol>m. भविष्य के विकास का पूर्वानुमान लगाना और संगठन, कार्मिक प्रबंधन और प्रक्रियाओं में आवश्यक बदलावों का सुझाव देना ताकि उन परिवर्तनों के अनुरूप प्रतिक्रिया दी जा सके।</ol>
