						<ul>
							<h5>(b) कल्याण प्रभाग:</h5>
						</ul>

						<ol>i) CBIC को कल्याणकारी उपायों की पहचान करना और उनकी सिफारिश करना।</ol>

						<ol>ii) फील्ड फॉर्मेशन से प्राप्त प्रस्तावों को संसाधित करना, ताकि कल्याण कोष की गवर्निंग बॉडी द्वारा निधियों की स्वीकृति प्राप्त हो सके।</ol>

						<ol>iii) लॉजिस्टिक्स निदेशालय और प्रधान CCA कार्यालय के साथ समन्वय करना, ताकि कल्याण कोष और विशेष उपकरण कोष के बीच वितरित की जाने वाली निधियों का लेखा-जोखा रखा जा सके।</ol>

						<ol>iv) कर्मचारियों की सेवानिवृत्ति को प्रबंधित करना, विशेष रूप से उनके मानसिक, भावनात्मक और वित्तीय पहलुओं को ध्यान में रखते हुए (NACEN और/या बाहरी विशेषज्ञों के माध्यम से प्रशिक्षण की व्यवस्था करके, ताकि सेवा से सेवानिवृत्ति के बाद जीवन के लिए मानसिक रूप से तैयार किया जा सके और सेवानिवृत्ति लाभों का सही प्रबंधन किया जा सके)।</ol>

						<ol>v) सेवानिवृत्त होने वाले अधिकारियों की विशेषज्ञता क्षेत्रों और कौशलों की सूची तैयार करना और बनाए रखना, और उन्हें उनके संबंधित क्षेत्रों के मंत्रालयों और सार्वजनिक उपक्रमों में अवसरों का पता लगाने की सलाह देना।</ol>

						<ol>vi) CBIC द्वारा प्रचारित/कार्यान्वित कल्याणकारी योजनाओं/उपायों की जानकारी अधिकारियों और कर्मचारियों के बीच वितरित करना।</ol>

