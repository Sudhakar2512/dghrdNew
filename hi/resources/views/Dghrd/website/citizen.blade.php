						<ol>ii) बुनियादी ढांचे से संबंधित सभी मामलों पर विचार करना, जिनमें भूमि की खरीद और निपटान, भवनों की खरीद और निपटान, आवास की किराये पर व्यवस्था, पहले से किराए पर लिए गए स्थान को जारी रखने, कार्यालय और आवासीय भवनों के निर्माण, मरम्मत/रखरखाव/नवीनीकरण/संशोधन/बदलाव आदि शामिल हैं।</ol>

						<ol>iii) CBIC की संपत्तियों का लेखा-जोखा रखना और प्रलेखन करना, जिसमें संपत्ति रजिस्टर (Asset Register) का निर्माण, रखरखाव और नियमित अद्यतन शामिल है।</ol>

						<ol>iv) विभागीय कर्मचारियों के लिए तैयार कार्यालय स्थान और आवासीय व्यवस्था की बजटीय आवश्यकताओं को संकलित करना और CBIC को प्रस्तुत करना।</ol>

						<ol>v) बुनियादी ढांचा प्रस्तावों (प्रक्रियाधीन या स्वीकृत) की नीति दिशानिर्देशों और प्रशासनिक निर्देशों के अनुरूपता सुनिश्चित करना।</ol>

						<ol>vi) CBIC और इसकी फील्ड फॉर्मेशन के बीच एक कड़ी के रूप में कार्य करना, ताकि प्रस्तुत प्रस्तावों पर मंत्रालय की टिप्पणियों/प्रश्नों/अनुमोदनों/स्वीकृतियों को फील्ड फॉर्मेशन तक पहुंचाया जा सके।</ol>
