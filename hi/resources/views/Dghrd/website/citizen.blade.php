							<h5>II. एचआरएम II विंग</h5>
						</ul>
						<ol>a. CBIC को उसकी वार्षिक भर्ती योजना (Annual Recruitment Plan - ARP) या प्रत्यक्ष भर्ती तैयार करने में सहायता प्रदान करना।</ol>

						<ol>b. CBIC को उसकी भर्ती नीति (Recruitment Policy) के निर्माण और कार्यान्वयन में समर्थन देना।</ol>

						<ol>c. मानव संसाधन नीतियों (HR Policies), प्रक्रियाओं और प्रणालियों को डिज़ाइन करना, जिसमें वे प्रस्ताव शामिल हैं जहां पदों को अस्थायी रूप से एक कार्यात्मक क्षेत्र से दूसरे में स्थानांतरित किया जाता है।</ol>

						<ol>d. प्रशिक्षण, पदस्थापन (Placement), कौशल उन्नयन (Skill Upgradation) और उत्तराधिकार योजना (Succession Planning) के लिए अधिकारियों/कर्मचारियों की सिफारिश हेतु मानव संसाधन सूचना प्रणाली (HRIS) को बनाए रखना और अपडेट करना।</ol>

						<ol>e. ग्रुप A अधिकारियों के लिए सिविल सूची (Civil List) और डिस्पोज़िशन सूची (Disposition List) को बनाए रखना और प्रकाशित करना।</ol>

						<ol>f. देशभर में फील्ड फॉर्मेशन द्वारा अपनाई जाने वाली प्रशासनिक प्रक्रियाओं में एकरूपता/समानता लाने में CBIC को सहायता प्रदान करना।</ol>

						<ol>g. अधिकारियों के पदस्थापन (Placement) और स्थानांतरण (Transfer) के लिए वार्षिक सामान्य स्थानांतरण (AGT) और अन्य मामलों में CBIC को डेटा समर्थन प्रदान करना।</ol>

						<ol>h. 56J के तहत समीक्षा के लिए अधिकारियों के प्रदर्शन की जांच करना।</ol>

						<ol>i. स्वच्छता कार्य योजना (Swachchta Action Plan) को लागू करना।</ol>

						<ol>j. स्थानांतरण नीति (Transfer Policy) पर प्रतिक्रिया प्राप्त करना और आगे की कार्रवाई के लिए इसे CBIC तक पहुंचाना।</ol>
